#[test]
fn separators_are_collapsed_headers_and_derived_mods_carry_the_chip() {
    let mut m = MeshesModel::empty();
    m.mods = vec![
        mod_row(5, "overwrite", 2, false),
        mod_row(4, "ParallaxGen_Output", 1, true),
        mod_row(3, "Meshes_separator", 3, false),
        mod_row(2, "Assorted mesh fixes", 1, false),
        mod_row(1, "Data", 0, false),
        mod_row(6, "Skyrim - Meshes0.bsa", 4, false),
    ];
    let mut h = harness(m);
    h.run();
    // A separator is a header named without its `_separator` suffix; its mods (listed above it) start hidden.
    h.get_by_label("\u{25bc} Meshes");
    assert!(h.query_by_label("Meshes_separator").is_none());
    assert!(h.query_by_label("ParallaxGen_Output").is_none());
    h.get_by_label("Assorted mesh fixes").click();
    h.run();
    assert_eq!(h.state().selected_mod, Some(2));
    h.get_by_label("\u{25bc} Meshes").click();
    h.run();
    assert_eq!(
        h.state().selected_mod,
        Some(2),
        "a header is not selectable"
    );
    assert!(h.state().expanded.contains(&3));
    h.get_by_label("ParallaxGen_Output");
    h.get_by_label("\u{25b2} Meshes");
    assert_eq!(
        h.query_all_by_label("Generated by PGPatcher").count(),
        1,
        "only the derived mod has the chip"
    );
}

