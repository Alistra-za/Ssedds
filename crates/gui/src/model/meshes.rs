/// What a slot holds: lighting slots are texture-set slots (§8 slot table); effect slots are source and greyscale.
pub fn slot_name(shader_kind: i32, slot: usize) -> &'static str {
    match (shader_kind, slot) {
        (2, 0) => "source",
        (2, 1) => "greyscale",
        (2, _) => "",
        (_, 0) => "diffuse",
        (_, 1) => "normal",
        (_, 2) => "glow/skin",
        (_, 3) => "height/detail",
        (_, 4) => "cubemap",
        (_, 5) => "env mask",
        (_, 6) => "inner/tint",
        (_, 7) => "backlight/specular",
        _ => "",
    }
}

