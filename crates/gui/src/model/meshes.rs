#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum NifFilter {
    #[default]
    All,
    Wins,
    Overridden,
    Conflicted,
    Problems,
}

impl NifFilter {
    pub const ALL: [NifFilter; 5] = [
        NifFilter::All,
        NifFilter::Wins,
        NifFilter::Overridden,
        NifFilter::Conflicted,
        NifFilter::Problems,
    ];
    pub fn label(self) -> &'static str {
        match self {
            NifFilter::All => "All",
            NifFilter::Wins => "Wins",
            NifFilter::Overridden => "Overridden",
            NifFilter::Conflicted => "Conflicted",
            NifFilter::Problems => "Problems",
        }
    }
    pub fn matches(self, n: &NifRow) -> bool {
        match self {
            NifFilter::All => true,
            NifFilter::Wins => n.wins,
            NifFilter::Overridden => !n.wins,
            NifFilter::Conflicted => n.n_copies > 1,
            NifFilter::Problems => n.problem.is_some(),
        }
    }
}

/// `p` without a leading `meshes/` or `meshes\` (any case): how mesh paths are shown. Display only.
pub fn display_path(p: &str) -> &str {
    let b = p.as_bytes();
    if b.len() >= 7 && b[..6].eq_ignore_ascii_case(b"meshes") && matches!(b[6], b'/' | b'\\') {
        &p[7..]
    } else {
        p
    }
}

