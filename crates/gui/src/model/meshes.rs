    /// `activate` with the MO2 detection result given: `(instance root, its selected profile)`.
    pub fn activate_with(&mut self, detected: Option<(PathBuf, String)>) {
        if self.activated {
            return;
        }
        self.activated = true;
        let s = &self.settings;
        self.target = match (&s.instance, &s.profile, &s.folder) {
            (Some(root), Some(profile), _) => Some(ScanTarget::Mo2 {
                root: root.clone(),
                profile: profile.clone(),
            }),
            (_, _, Some(f)) => Some(ScanTarget::Folder(f.clone())),
            _ => None,
        };
        if let Some((root, profile)) = detected {
            if s.instance.as_ref() != Some(&root) && s.folder.is_none() {
                self.dialog = Some(MeshesDialog::Mo2 { root, profile });
            }
        }
        self.read_profiles();
        self.v3.locate(self.target.clone());
        if let Some(p) = self.store_path.clone() {
            match Store::open(&p) {
                Ok(store) => {
                    self.store = Some(store);
                    self.reload();
                }
                Err(e) => self.error = Some(db_err(format!("{}: {e}", p.display()))),
            }
        }
    }

